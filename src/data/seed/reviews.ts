let seq = 0
function build(rows: Row[], targetType: Review['targetType']): Review[] {
  return rows.map(([showId, targetId, rating, text]) => {
    seq += 1
    const rng = makeRng(`review-${targetType}-${seq}`)
    // 지난 공연(09/02~09/04) 직후에 작성된 것으로 배치
    const day = rngInt(rng, 3, 5)
    return {
      id: `rv${seq}`,
      showId,
      targetType,
      targetId,
      rating,
      text,
      authorName: rngPick(rng, NAMES),
      createdAt: kstIso(Y, M, day, rngInt(rng, 9, 23), rngInt(rng, 0, 59)),
    }
  })
}

