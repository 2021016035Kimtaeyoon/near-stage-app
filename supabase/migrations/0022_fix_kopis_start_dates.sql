-- ============================================================
-- 등록 공연의 날짜 복구 — 지어낸 값 걷어내기.
--
-- 증상: 9월 17일 하루짜리인 '재능 혜화 마티네'가 9월 7일부터 17일까지
--       열하루 내내 날짜 탭에 떴습니다.
--
-- 원인 두 가지, 둘 다 우리가 만든 것입니다.
--
--   ① 동기화 함수의 정규식이 깨져 있어서(모든 문자를 '-' 로 바꾸는 replace)
--      공연 100건 전부 starts_at 이 동기화 날짜(2026-09-07)로 찍혔습니다.
--      0017 에서 종료일만 복구했기 때문에 "9월 7일 시작 ~ 9월 17일 종료"라는
--      있지도 않은 11일짜리 기간이 만들어졌고, 기간 겹침으로 거르니 열하루
--      모두에 걸렸습니다.
--
--   ② 0017 의 마지막 UPDATE 가 기간을 못 읽은 20건에 `now() + 14 days` 를
--      넣었습니다. "다음 동기화에서 정확한 값으로 덮인다"고 적어뒀지만 동기화가
--      한 번도 돌지 않았고, 그래서 20건이 전부 종료일 2026-09-22 로 똑같습니다.
--      이건 데이터가 아니라 우리가 지어낸 숫자입니다.
-- ============================================================

-- ─────────── ① 시작일 복구 ───────────
--
-- 설명문이 '서양음악(클래식) · 2026.09.17 ~ 2026.09.17' 형태라, 0017 이 뒤 날짜를
-- 쓴 것처럼 앞 날짜를 씁니다.
--
-- ★ 시각(11:00 같은)은 건드리지 않습니다. KOPIS 시간 안내에서 제대로 뽑은
--   값이라 맞습니다. 틀린 것은 날짜뿐입니다.
--
-- ★ regexp_matches 는 집합을 반환해서 UPDATE ... SET 안에서 못 씁니다(0A000).
--   0017 에서 겪은 그대로 substring(x from '...') 을 씁니다.

update public.shows s
set starts_at = (
  (
    replace(substring(s.description from '(\d{4}\.\d{2}\.\d{2})\s*~'), '.', '-')::date
    + (s.starts_at at time zone 'Asia/Seoul')::time
  ) at time zone 'Asia/Seoul'
)
where s.source = 'kopis'
  and s.description ~ '\d{4}\.\d{2}\.\d{2}\s*~'
  -- 이미 맞는 행은 건드리지 않습니다 (다시 돌려도 안전)
  and (s.starts_at at time zone 'Asia/Seoul')::date
      <> replace(substring(s.description from '(\d{4}\.\d{2}\.\d{2})\s*~'), '.', '-')::date;

-- ─────────── ② 지어낸 종료일 지우기 ───────────
--
-- 0017 이 값을 채운 조건은 "설명문이 날짜로 끝날 것"이었습니다. 그 조건에
-- 걸리지 않은 행(줄거리가 들어 있는 20건)이 `now() + 14 days` 를 받았습니다.
--
-- ★ 지우면 그 공연들은 목록에서 사라집니다. starts_at 도 못 고친 행이라
--   시작 시각 + 공연 시간이 이미 지난 것으로 계산되기 때문입니다.
--   그래도 지웁니다 — 언제 하는지 모르는 공연을 9월 7일부터 22일까지 매일
--   "이 날 합니다"라고 보여주는 것보다, 안 보이는 편이 정직합니다.
--   동기화를 한 번 돌리면 kopis_id 로 덮어써지며 제 날짜로 돌아옵니다.
--
-- ★ 행을 지우지 않고 종료일만 비웁니다. 좋아요 같은 것이 달려 있을 수 있고,
--   행을 지우면 그것도 같이 사라집니다.

update public.shows
set run_ends_at = null
where source = 'kopis'
  and run_ends_at is not null
  and description !~ '(\d{4}\.\d{2}\.\d{2})\s*$';

-- ─────────── ③ 뒤집힌 기간 방어 ───────────
--
-- 시작일이 종료일보다 뒤인 행이 남으면 어느 날짜에도 걸리지 않고 목록에서
-- 조용히 사라집니다. 그런 행은 종료일을 시작일에 맞춥니다.

update public.shows
set run_ends_at = starts_at + make_interval(mins => greatest(duration_min, 60))
where source = 'kopis'
  and run_ends_at is not null
  and run_ends_at < starts_at;

