-- 날짜가 제각각으로 흩어져 있어야 합니다. 한 날짜에 몰려 있으면 안 된 것입니다.
--
-- ★ 이걸로도 안 고쳐지는 것이 하나 남습니다.
--   기간 공연 33건(최장 74일)은 그 기간의 모든 날짜에 계속 뜹니다. KOPIS 가
--   주는 것은 '기간'이지 '무슨 요일에 공연하는지'가 아니기 때문입니다.
--   요일은 상세 API 의 dtguidance('화요일 ~ 금요일(20:00), 토요일(15:00)')
--   에 있는데 지금은 첫 시각만 뽑아 쓰고 버립니다. 저장한 뒤에야 판단할 수
--   있어서, 그 전까지는 화면에 "기간 공연 N건은 예매처에서 확인하세요"라고
--   밝힙니다 — 없는 정보로 추측하지 않습니다.
